#!/usr/bin/env python3
"""Compile the checked-in catalog, without network access."""
import csv,json,itertools
from pathlib import Path
rows=list(csv.DictReader(open('data/stars.csv')))
lines=['/* HYG v4.1 extract, CC BY-SA 4.0, with IAU WGSN names. See data/README.md. Generated by tools/compile_stars.py. */']
lines+=['const CatalogStar star_catalog[] = {']
# The nine starter-route keys around home are never a catalog star's.
used={(x,0,z) for x in range(-1,2) for z in range(-1,2)}
keys=[]
for r in rows:
 xyz=[int(r[a+'_mly']) for a in 'xyz']
 sector=tuple(round(x/1000) for x in xyz)
 if r['name']=='Sol':sector=(0,-1,0)
 # A taken key moves to the nearest free one, widening the search as needed.
 reach=1
 while sector in used:
  free=[tuple(sector[i]+d[i] for i in range(3)) for d in itertools.product(range(-reach,reach+1),repeat=3)]
  free=[c for c in free if c not in used]
  if free:sector=min(free,key=lambda c:(sum((c[i]*1000-xyz[i])**2 for i in range(3)),c))
  reach+=1
 used.add(sector);keys.append(sector)
 # Slash can denote uncertain alternatives in HYG. Only explicit curated
 # component lists have multiple complete classes.
 spec=r['spectra'].split('/')
 if len(spec)>1 and len(spec[0])<3:spec=[spec[0]]
 assert len(r['name'])<24 and len(spec)<=6
 lines.append('    {%s,%s,{%s},{%s},%d,{%s}},'%(json.dumps(r['name']),json.dumps(r['aliases']),','.join(map(str,xyz)),','.join(map(str,sector)),len(spec),','.join(json.dumps(s) for s in spec)))
lines+=['};','const int star_catalog_count = sizeof(star_catalog)/sizeof(star_catalog[0]);']
# Catalog indices in sector order (x, then y, then z), for binary search.
order=sorted(range(len(keys)),key=lambda i:keys[i])
lines+=['static const uint16_t star_catalog_order[] = {']
lines+=['    '+','.join(map(str,order[i:i+20]))+',' for i in range(0,len(order),20)]
lines+=['};']
Path('src/star_catalog.inc').write_text('\n'.join(lines)+'\n')
