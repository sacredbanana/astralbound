#!/usr/bin/env python3
"""Offline, exact apportionment of one billion systems into a finite disc."""
import csv,math
from pathlib import Path
TOTAL=1_000_000_000
pins=[tuple(int(r[k]) for k in ('x_mly','y_mly','z_mly')) for r in csv.DictReader(open('data/stars.csv'))]
# Catalog sector keys are unique; the nine original starter-route keys are separate.
reserved=len(pins)+9
weights=[]
for iy in range(10):
 for iz in range(10):
  for ix in range(10):
   x=ix*2000-9000;z=iz*2000-9000;y=iy*60-270
   far=math.hypot(abs(x)+1000,abs(z)+1000)
   r=math.hypot(x,z)
   if far>10000:weights.append(0);continue
   yaw=round(math.atan2(x,z)*1024/(2*math.pi))
   arm=(yaw-int(r/16))%256;arm=min(arm,256-arm)
   disc=int((10000-r)*(300-abs(y))/30000)
   weights.append(max(1,5+disc+(128-arm)//3+(25 if r<1000 else 0)))
budget=TOTAL-reserved;den=sum(weights)
quotas=[budget*w//den for w in weights]
order=sorted(range(1000),key=lambda i:budget*weights[i]%den,reverse=True)
for i in order[:budget-sum(quotas)]:quotas[i]+=1
assert sum(quotas)+reserved==TOTAL and max(quotas)<240_000_000
lines=['/* Generated by tools/compile_population.py; exact finite population quotas. */','static const PopulationCell population_cells[1000] = {']
start=0
for q in quotas:
 lines.append('    {%dU,%dU},'%(start,q));start+=q
lines+=['};','#define POPULATION_RESERVED %dU'%reserved]
Path('src/population.inc').write_text('\n'.join(lines)+'\n')
print(TOTAL,'systems;',reserved,'reserved;',sum(q>0 for q in quotas),'populated cells')
