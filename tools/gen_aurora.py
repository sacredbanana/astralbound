#!/usr/bin/env python3
"""Generate exact aurora tables from the game's Q14 sine table.

No floating point or altered rounding: division of signed values truncates
like C99. Run with --check to verify the committed header is reproducible.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
TRIG = ROOT / 'src/trig.h'
OUTPUT = ROOT / 'src/aurora_tables.h'


def generate():
    sine = list(map(int, re.findall(r'-?\d+', TRIG.read_text().split('{', 1)[1])))
    assert len(sine) == 1024

    def trunc(n, d):
        return n // d if n >= 0 else -((-n) // d)

    def table(name, kind, dimensions, rows):
        return f'static const {kind} {name}{dimensions} = {{\n' + ',\n'.join(rows) + '\n};\n'

    parts = ['/* SPDX-License-Identifier: Unlicense; generated by tools/gen_aurora.py.\n'
             '   Exact C99 truncation of src/trig.h; no runtime initialization. */\n'
             '#ifndef ASTRALBOUND_AURORA_TABLES_H\n#define ASTRALBOUND_AURORA_TABLES_H\n'
             'typedef struct { int8_t latitude5, latitude2, fold48, fold24; } AuroraWave;\n']
    parts.append(table('aurora_wave', 'AuroraWave', '[1024]', [
        '    {' + ','.join(str(trunc(s * m, 16384)) for m in (5, 2, 48, 24)) + '}'
        for s in sine]))
    for name, angles, size in [('aurora_circle', range(0, 1024, 4), 256),
                               ('aurora_latitude', range(183, 198), 15),
                               ('aurora_tilt', range(28, 40), 12)]:
        parts.append(table(name, 'int16_t', f'[{size}][2]', [
            f'    {{{sine[a]}, {sine[(a + 256) & 1023]}}}' for a in angles]))
    fade = [n * 16 // 5000 for n in range(5001)]
    parts.append(table('aurora_fade', 'uint8_t', '[5001]', [
        '    ' + ','.join(map(str, fade[i:i + 32])) for i in range(0, len(fade), 32)]))
    parts.append(table('aurora_strength', 'uint8_t', '[17][145]', [
        '    {' + ','.join(str(f * fold // 256) for fold in range(120, 265)) + '}'
        for f in range(17)]))
    parts.append(table('aurora_density', 'uint8_t', '[3][17]', [
        '    {' + ','.join(str(opacity * s // 16) for s in range(17)) + '}'
        for opacity in (16, 12, 7)]))
    parts.append('#endif\n')
    return '\n'.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.error(f'{OUTPUT} is stale; run tools/gen_aurora.py')
    else:
        OUTPUT.write_text(generated)


if __name__ == '__main__':
    main()
