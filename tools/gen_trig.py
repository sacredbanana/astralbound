#!/usr/bin/env python3
"""Generate the original Q14 trigonometry table; no runtime floating point."""
from pathlib import Path
import math
p = Path(__file__).resolve().parents[1] / 'src/trig.h'
p.write_text('/* SPDX-License-Identifier: Unlicense; generated by tools/gen_trig.py */\nstatic const short sine_table[1024] = {\n' + ',\n'.join(','.join(str(round(math.sin(i*math.tau/1024)*16384)) for i in range(j,j+16)) for j in range(0,1024,16)) + '\n};\n')
